/*
 * API used by the web interface (webapp/): richer DTOs than the original
 * endpoints, pagination through server-side continuation tokens, channels and
 * comments. The original /api/... routes stay unchanged for existing clients.
 */

@Serializable
data class ItemDto(
    val url: String,
    val title: String,
    /** "video", "channel" or "playlist". */
    val kind: String,
    val uploaderName: String = "",
    val uploaderUrl: String = "",
    val uploaderAvatarUrl: String = "",
    val thumbnailUrl: String = "",
    val durationText: String = "",
    val durationSeconds: Long = 0,
    val viewCount: Long = -1,
    val uploadedText: String = "",
    val subscriberCount: Long = -1,
    val isLive: Boolean = false
)

@Serializable
data class PageDto(val items: List<ItemDto>, val nextPage: String? = null)

@Serializable
data class SubtitleDto(
    val languageTag: String,
    val label: String,
    val autoGenerated: Boolean,
    val mimeType: String,
    /** Relayed through /api/stream: the browser cannot fetch YouTube's timed text directly. */
    val url: String
)

@Serializable
data class WatchDto(
    val url: String,
    val title: String,
    val description: String,
    /** "html", "markdown" or "text". */
    val descriptionFormat: String,
    val uploadedText: String,
    val uploaderName: String,
    val uploaderUrl: String,
    val uploaderAvatarUrl: String,
    val uploaderSubscriberCount: Long,
    val uploaderVerified: Boolean,
    val viewCount: Long,
    val likeCount: Long,
    val durationSeconds: Long,
    val thumbnailUrl: String,
    val isLive: Boolean,
    val tags: List<String>,
    val subtitles: List<SubtitleDto>,
    val related: List<ItemDto>
)

@Serializable
data class ChannelDto(
    val url: String,
    val name: String,
    val avatarUrl: String,
    val bannerUrl: String,
